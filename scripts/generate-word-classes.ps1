$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path $PSScriptRoot -Parent
$sourcePath = Join-Path $repoRoot 'notepad_plus_plus/scintilla/src/CharacterCategoryMap.cxx'
$sourceText = [IO.File]::ReadAllText($sourcePath)
$table = [regex]::Match($sourceText, 'const int catRanges\[\] = \{([\s\S]*?)\};').Groups[1].Value
$entries = [regex]::Matches($table, '(?m)^([0-9]+),')
if ($entries.Count -lt 3000) { throw 'Unexpected source category table' }
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by scripts/generate-word-classes.ps1 from the supplied Scintilla Unicode 16.0.0 table.')
$lines.Add('// Derived from CharacterCategoryMap.cxx, Copyright 2013 by Neil Hodgson <neilh@scintilla.org>.')
$license = Get-Content -LiteralPath (Join-Path $repoRoot 'notepad_plus_plus/scintilla/License.txt')
foreach ($line in $license) { $lines.Add('// ' + $line) }
$lines.Add('// Entries pack a Unicode range start in the high bits and a word class in the low two bits.')
$lines.Add('pub(super) const RANGES: &[u32] = &[')
$previousClass = -1
foreach ($entry in $entries) {
    $packed = [int]::Parse($entry.Groups[1].Value)
    $category = $packed -band 31
    $class = if ($category -le 10) { 0 } elseif ($category -le 21) { 1 } elseif ($category -eq 23 -or $category -eq 24) { 3 } else { 2 }
    if ($class -ne $previousClass) {
        $lines.Add('    ' + ((($packed -shr 5) -shl 2) -bor $class) + ',')
        $previousClass = $class
    }
}
$lines.Add('];')
[IO.File]::WriteAllText((Join-Path $repoRoot 'crates/editor-core/src/word_classes_data.rs'), ($lines -join "`n") + "`n")
