"""Generate lexer/style profiles from the supplied Notepad++ sources."""
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / "notepad_plus_plus/PowerEditor/src"
languages = {x.attrib["name"]: x for x in ET.parse(source / "langs.model.xml").findall(".//Language")}
styles = {x.attrib["name"]: x for x in ET.parse(source / "stylers.model.xml").findall(".//LexerType")}
view = (source / "ScintillaComponent/ScintillaEditView.cpp").read_text(encoding="utf-8-sig")
lexers = dict(re.findall(r'\{L"([^"]+)"[^\n]+?,\s*"([^"]+)"\}', view))
registry = (root / "Windows/src/languages.rs").read_text(encoding="utf-8")
commands = re.findall(r"command: (IDM_LANG_\w+)", registry)
aliases = dict(text="normal", js="javascript.js", golang="go", fortran_77="fortran77",
               ps="postscript", sttxt="fcST", ascii="nfo", flash="actionscript", au3="autoit")
quote = lambda s: json.dumps(s, ensure_ascii=False)
color = lambda s: int(s[4:6] + s[2:4] + s[0:2], 16)
output = [
    "// Generated by scripts/generate-syntax.py from the bundled Notepad++ sources.",
    "use npp_compat::commands::*;",
    "pub struct Style { pub id: usize, pub fore: u32, pub back: u32, pub flags: u32, pub protected: bool }",
    "pub struct Syntax { pub lexer: &'static str, pub keywords: &'static [(usize, &'static str)], pub styles: &'static [Style] }",
    "pub fn lookup(command: u32) -> Option<&'static Syntax> { match command {",
]
for command in commands:
    key = command.removeprefix("IDM_LANG_").lower()
    key = aliases.get(key, key)
    model = languages[key]
    lexer = lexers[key]
    keywords = []
    for item in model.findall("Keywords"):
        index = {"instre1": 0, "instre2": 1, **{f"type{i}": i + 1 for i in range(1, 8)}}.get(item.attrib["name"])
        if lexer in ("cpp", "objc"):
            index = dict(instre1=0, type1=1, type2=2, instre2=3).get(item.attrib["name"])
        if index is not None and item.text and item.text.strip():
            keywords.append((index, item.text.strip()))
    output.append(f"{command} => Some(&Syntax {{ lexer: {quote(lexer)}, keywords: &[" +
                  ",".join(f"({i}, {quote(s)})" for i, s in keywords) + "], styles: &[")
    if key in styles:
        for item in styles[key].findall("WordsStyle"):
            a = item.attrib
            style = int(a.get("styleID", "0"))
            fg, bg = a.get("fgColor", "000000"), a.get("bgColor", "FFFFFF")
            if style < 0 or style > 255 or not re.fullmatch("[0-9a-fA-F]{12}", fg + bg):
                continue
            protected = any(word in a.get("name", "").upper() for word in
                            ("STRING", "COMMENT", "CHARACTER", "REGEX", "LITERAL", "HEREDOC"))
            # YAML block scalars contain significant indentation and whitespace.
            protected |= key == "yaml" and a.get("name", "").upper() == "TEXT"
            output.append(f"Style {{ id: {style}, fore: {color(fg)}, back: {color(bg)}, " +
                          f"flags: {int(a.get('fontStyle', '0') or 0)}, protected: {str(protected).lower()} }},")
    output.append("] }),")
output.extend(["_ => None,", "} }"])
(root / "Windows/src/syntax_data.rs").write_text("\n".join(output) + "\n", encoding="utf-8")
print(f"Generated {len(commands)} language syntax profiles")
